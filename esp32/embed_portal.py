"""Embed the Wi-Fi setup portal (portal/) into src/portal_assets.h.

Runs before every PlatformIO build (`extra_scripts = pre:embed_portal.py`) and
from the command line:

    python3 embed_portal.py          # regenerate
    python3 embed_portal.py --check  # fail if src/portal_assets.h is stale

The pages are stored in flash (PROGMEM) and served as-is by
src/wifi_provisioning.cpp; the local preview (portal-preview/server.py) serves
the same files, so what you see there is what the device sends.
"""

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

try:
    Import("env")  # noqa: F821 - provided by PlatformIO/SCons, which has no __file__
    HERE = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    env = None
    HERE = Path(__file__).resolve().parent
PORTAL = HERE / "portal"
OUTPUT = HERE / "src" / "portal_assets.h"
DELIMITER = "WGPORTAL"

# (route, file, content type). Routes follow the preview server.
ASSETS = (
    ("/", "wifi.html", "text/html; charset=utf-8"),
    ("/wifi", "wifi.html", "text/html; charset=utf-8"),
    ("/connect", "connect.html", "text/html; charset=utf-8"),
    ("/static/wignet-portal.css", "wignet-portal.css", "text/css; charset=utf-8"),
    ("/static/portal.css", "portal.css", "text/css; charset=utf-8"),
    ("/static/portal.js", "portal.js", "application/javascript; charset=utf-8"),
)


def symbol(name: str) -> str:
    return "PORTAL_" + name.upper().replace(".", "_").replace("-", "_")


def versions() -> dict[str, str]:
    """A short content hash per /static file: pages ask for /static/x?v=<hash>,
    so the phone may keep them (src/wifi_provisioning.cpp) and a firmware with
    other files is always fetched afresh."""
    return {route: hashlib.sha256((PORTAL / name).read_bytes()).hexdigest()[:10]
            for route, name, _ in ASSETS if route.startswith("/static/")}


def versioned(text: str, hashes: dict[str, str]) -> str:
    return re.sub(r'(["\'])(/static/[^"\'?]+)(["\'])',
                  lambda m: f"{m[1]}{m[2]}?v={hashes[m[2]]}{m[3]}" if m[2] in hashes else m[0],
                  text)


def render() -> str:
    hashes = versions()
    files = sorted({name for _, name, _ in ASSETS})
    lines = [
        "// Generated by esp32/embed_portal.py from esp32/portal/. Do not edit.",
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
    ]
    total = 0
    for name in files:
        text = (PORTAL / name).read_text(encoding="utf-8")
        if name.endswith(".html"):
            text = versioned(text, hashes)
        if f"){DELIMITER}\"" in text:
            raise SystemExit(f"{name} contains the raw-string delimiter {DELIMITER}")
        size = len(text.encode("utf-8"))
        total += size
        lines.append(f"// {name}: {size} bytes")
        lines.append(f'static const char {symbol(name)}[] PROGMEM = R"{DELIMITER}({text}){DELIMITER}";')
        lines.append("")
    lines += [
        f"// {total} bytes in flash in total.",
        "struct PortalAsset {",
        "  const char *path;",
        "  const char *contentType;",
        "  PGM_P body;",
        "  size_t length;",
        "};",
        "",
        "static const PortalAsset PORTAL_ASSETS[] = {",
    ]
    for route, name, content_type in ASSETS:
        lines.append(f'    {{"{route}", "{content_type}", {symbol(name)}, sizeof({symbol(name)}) - 1}},')
    lines += ["};", ""]
    return "\n".join(lines)


def main(check: bool) -> int:
    content = render()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if content == current:
        return 0
    if check:
        print(f"{OUTPUT.relative_to(HERE)} is out of date; run python3 embed_portal.py")
        return 1
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"[portal] wrote {OUTPUT.relative_to(HERE)}")
    return 0


if env is not None:
    main(check=False)
elif __name__ == "__main__":
    sys.exit(main(check="--check" in sys.argv[1:]))
