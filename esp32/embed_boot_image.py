"""Embed the LCD boot picture (assets/boot_lcd154.png) into src/boot_image.h.

Runs before the waveshare_esp32s3_lcd_154 build
(`extra_scripts = pre:embed_boot_image.py`) and from the command line:

    python3 embed_boot_image.py          # regenerate
    python3 embed_boot_image.py --check  # fail if src/boot_image.h is stale

The PNG goes in as-is: the firmware decodes it at power-on, blends its
transparency onto the boot background and centres it (main.cpp,
lcdBootScreen), so swapping the picture needs no code change. At most the
panel's size, 240x240.
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

try:
    Import("env")  # noqa: F821 - provided by PlatformIO/SCons, which has no __file__
    HERE = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    env = None
    HERE = Path(__file__).resolve().parent
SOURCE = HERE / "assets" / "boot_lcd154.png"
OUTPUT = HERE / "src" / "boot_image.h"
PANEL = 240


def render() -> str:
    data = SOURCE.read_bytes()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit(f"{SOURCE} is not a PNG")
    width, height = struct.unpack(">II", data[16:24])
    if width > PANEL or height > PANEL:
        raise SystemExit(f"{SOURCE} is {width}x{height}; the panel is {PANEL}x{PANEL}")
    lines = [
        "// Generated by esp32/embed_boot_image.py from esp32/assets/boot_lcd154.png. Do not edit.",
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        f"// {width}x{height} PNG, {len(data)} bytes",
        "static const uint8_t BOOT_IMAGE_PNG[] PROGMEM = {",
    ]
    for start in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[start:start + 16]) + ",")
    lines += ["};", ""]
    return "\n".join(lines)


def main(check: bool = False) -> int:
    text = render()
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
    if current == text:
        return 0
    if check:
        print(f"{OUTPUT} is stale; run python3 embed_boot_image.py", file=sys.stderr)
        return 1
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"[boot image] wrote {OUTPUT.name}")
    return 0


if env is not None:
    main()
elif __name__ == "__main__":
    sys.exit(main("--check" in sys.argv[1:]))
