"""Stamp the firmware with the git commit it was built from.

Runs before every PlatformIO build (`extra_scripts = pre:firmware_version.py`,
after embed_portal.py so a regenerated portal_assets.h counts) and from the
command line:

    python3 firmware_version.py      # print the version and write the header

The version is the short commit of HEAD, plus `-dirty.<hash>` when a build
input differs from that commit. The hash covers the uncommitted diff and the
untracked build inputs, so two dirty builds of the same tree carry the same
version and a flashed image can still be traced to its exact source. A tree
without git gives `unknown`.

The device sends the version on every /schedule poll (`&fw=`); the backoffice
parses it in backoffice/firmware_version.py and keeps the same list of build
inputs to count how many firmware commits a device is behind.

The value goes into src/firmware_version_gen.h (gitignored), rewritten only
when it changes, so only the files that include it recompile.
src/config.h is gitignored too and is not covered: it carries the local
host and credentials, not firmware behaviour.
"""

from __future__ import annotations

import hashlib
import subprocess
from pathlib import Path

try:
    Import("env")  # noqa: F821 - provided by PlatformIO/SCons, which has no __file__
    HERE = Path(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    env = None
    HERE = Path(__file__).resolve().parent
OUTPUT = HERE / "src" / "firmware_version_gen.h"

# Build inputs, relative to this directory. Keep in step with
# FIRMWARE_PATHS in backoffice/firmware_version.py.
BUILD_INPUTS = (
    "src",
    "portal",
    "platformio.ini",
    "embed_portal.py",
    "optimize_gxepd2.py",
    "firmware_version.py",
)


def _git(*args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(HERE), *args],
        check=True, capture_output=True, text=True,
    ).stdout


def firmware_version() -> str:
    try:
        commit = _git("rev-parse", "--short=12", "HEAD").strip()
        diff = _git("diff", "HEAD", "--binary", "--", *BUILD_INPUTS)
        untracked = _git("ls-files", "--others", "--exclude-standard",
                         "--", *BUILD_INPUTS).split()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    if not diff and not untracked:
        return commit
    digest = hashlib.sha256(diff.encode())
    for name in sorted(untracked):
        digest.update(name.encode())
        digest.update((HERE / name).read_bytes())
    return f"{commit}-dirty.{digest.hexdigest()[:8]}"


def write_header(version: str) -> None:
    content = (
        "// Generated by firmware_version.py - do not edit or commit.\n"
        "#pragma once\n"
        f'#define WIGNET_FW_VERSION "{version}"\n'
    )
    if not OUTPUT.exists() or OUTPUT.read_text() != content:
        OUTPUT.write_text(content)


VERSION = firmware_version()
write_header(VERSION)
print(f"Firmware version: {VERSION}")

# The build target, sent on /schedule as `&hw=` (backoffice/power.py) so the
# platform can tell boards apart. It is the PlatformIO environment's name,
# unless an environment fixes its board id itself (docs/ota.md "Board ids":
# the ota1 environment is the photopainter board, not a board of its own).
if env is not None:  # noqa: F821
    defined = [d[0] if isinstance(d, (tuple, list)) else d for d in env.get("CPPDEFINES", [])]  # noqa: F821
    if "WIGNET_HW_TARGET" not in defined:
        env.Append(CPPDEFINES=[("WIGNET_HW_TARGET", env.StringifyMacro(env["PIOENV"]))])  # noqa: F821
